/**
 * Generates src/theme/palette.css: Tailwind's colour palettes as CSS
 * variables, with a night (dark) variant of each.
 *
 *   node scripts/generate-theme.cjs
 *
 * How the theme works:
 * - tailwind.config.js points the themed palettes (stone, amber, ...) at
 *   these variables, so `bg-stone-50`, `text-amber-700` etc. follow the theme
 *   without any `dark:` classes in the components.
 * - Day = Tailwind's original values. Night = the scale mirrored (50<->950,
 *   100<->900, ...), so light surfaces become dark and dark text becomes light
 *   while every pairing keeps its contrast. Stone, gray and white get
 *   hand-tuned night values for proper surface layering.
 * - `.scheme-fixed` keeps the day values in both themes (for parts designed
 *   dark on purpose, like the footer and the dashboard sidebar).
 * - `.scheme-flip` uses the opposite of the current theme (for the home page,
 *   which is designed dark: dark at night, light by day).
 */
const fs = require("fs");
const path = require("path");
const colors = require("tailwindcss/colors");

const THEMED = ["stone", "gray", "amber", "yellow", "orange", "red", "rose", "pink", "emerald", "green", "lime", "teal", "sky", "blue", "indigo", "violet", "purple"];
const SHADES = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];

const rgb = (hex) => {
  const n = parseInt(hex.replace("#", ""), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};

// Night surfaces for the neutral greys: page, card, raised fill, border, ...
// then increasingly light text tones.
const NIGHT_NEUTRAL = {
  white: "28 25 23",
  50: "12 10 9",
  100: "37 33 31",
  200: "52 47 44",
  300: "73 68 64",
  400: "120 113 108",
  500: "168 162 158",
  600: "200 195 191",
  700: "220 216 213",
  800: "235 232 230",
  900: "245 245 244",
  950: "250 250 249",
};

const day = [`  --c-white: 255 255 255;`];
const night = [`  --c-white: ${NIGHT_NEUTRAL.white};`];

for (const name of THEMED) {
  SHADES.forEach((shade, i) => {
    day.push(`  --c-${name}-${shade}: ${rgb(colors[name][shade])};`);
    const nightValue =
      name === "stone" || name === "gray"
        ? NIGHT_NEUTRAL[shade]
        : rgb(colors[name][SHADES[SHADES.length - 1 - i]]);
    night.push(`  --c-${name}-${shade}: ${nightValue};`);
  });
}

const block = (selector, lines) => `${selector} {\n${lines.join("\n")}\n}\n`;

const css = `/* Generated by scripts/generate-theme.cjs. Do not edit by hand. */

${block(":root,\n.scheme-fixed,\n.dark .scheme-flip", day)}
${block(".dark,\n.dark .scheme-fixed .scheme-flip,\n:root:not(.dark) .scheme-flip", night)}`;

const out = path.resolve(__dirname, "../src/theme/palette.css");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, css);

// The matching Tailwind colour config.
const tw = { white: "rgb(var(--c-white) / <alpha-value>)" };
for (const name of THEMED) {
  tw[name] = Object.fromEntries(SHADES.map((s) => [s, `rgb(var(--c-${name}-${s}) / <alpha-value>)`]));
}
fs.writeFileSync(path.resolve(__dirname, "../src/theme/palette.tailwind.json"), JSON.stringify(tw, null, 2));

console.log(`Wrote ${path.relative(process.cwd(), out)} (${THEMED.length} palettes)`);
